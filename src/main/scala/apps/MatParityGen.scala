  def main(args: Array[String]): Unit =
    val root = sys.props.getOrElse("user.dir", ".")
    val dir  = s"$root/test-data/mat-parity"
    java.nio.file.Files.createDirectories(dir.asPath)

    val maxN   = sizes.max
    val all    = corpus(maxN)
    val allExp = corpusExp(maxN)

    val sb = StringBuilder()
    sb ++= header
    for n <- sizes.sorted do
      val m  = MatD(java.util.Arrays.copyOfRange(all, 0, n))
      val me = MatD(java.util.Arrays.copyOfRange(allExp, 0, n))
      for (label, value) <- cases(m) do
        sb ++= s"$n $label ${hex(value)}\n"
      for (label, word) <- expCases(me) do
        sb ++= f"$n $label $word%016x\n"
      println(s"  n=$n: ${cases(m).length + expCases(me).length} cases")

    for (rows, cols) <- shapes do
      val m  = mat2d(all, rows, cols)
      val me = mat2d(allExp, rows, cols)
      for (label, value) <- cases2d(m) do
        sb ++= s"${rows}x$cols $label ${hex(value)}\n"
      for (label, word) <- wordCases2d(m) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      for (label, word) <- mathCases(me) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      for (label, word) <- linalgCases(me) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      for (label, word) <- utilCases(m) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      for (label, word) <- pandasCases(m) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      for (label, word) <- signalCases(me) do
        sb ++= f"${rows}x$cols $label $word%016x\n"
      println(s"  ${rows}x$cols: ${cases2d(m).length + wordCases2d(m).length + mathCases(me).length + linalgCases(me).length + utilCases(m).length + pandasCases(m).length + signalCases(me).length} cases")

    for (name, arr) <- adversarial do
      for (orient, m) <- advShapes(arr) do
        for (label, word) <- advCases(m) do
          sb ++= f"adv/$name/$orient $label $word%016x\n"
      println(s"  adv/$name: ${advShapes(arr).length * advCases(advShapes(arr).head._2).length} cases")

    val out = s"$dir/scala-reference.txt"
    java.nio.file.Files.writeString(out.asPath, sb.toString)
    println(s"wrote $out")
    FixtureGuard.warnIfIgnored(dir.asPath)
